        severity = "minor"
        if result.condition_change in ["injured", "critical"]:
            severity = "major"
        if result.encounter_survived:
            severity = "notable"
        if result.discovery:
            severity = "notable"

        print(f"    >>> JOURNAL ENTRY ({severity}): {result.situation.situation_type.value}")
