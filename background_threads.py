@dataclass
class BackgroundSituation:
    """A situation generated for a separated character."""
    situation_type: SituationType
    description: str
    options: List[str]  # Possible responses
    difficulty: int  # 1-10, affects outcomes
    potential_rewards: List[str]
    potential_risks: List[str]
    time_pressure: bool  # Must act quickly?


@dataclass
class BackgroundTickResult:
    """Result of processing a background tick for a character."""
    character_id: str
    character_name: str
    situation: BackgroundSituation
    response: str  # What the character did
    outcome: str  # What happened
    condition_change: Optional[str]
    supplies_change: Optional[str]
    morale_change: Optional[str]
    discovery: Optional[str]
    encounter_survived: bool
    new_ally: Optional[str]
    new_enemy: Optional[str]


class BackgroundTickProcessor:
    """
    Processes background ticks for separated characters.

    Each tick:
    1. Generates a situation based on character's drive and world state
    2. Asks the character's model to respond
    3. Resolves the outcome
    4. Updates character state
    5. Logs to journal
    """

    def __init__(
        self,
        tracker: AutopilotTracker = None,
        ollama_generate: Callable = None,
        dm_generate: Callable = None,
    ):
        self.tracker = tracker or get_autopilot_tracker()
        self.ollama_generate = ollama_generate  # For character responses
        self.dm_generate = dm_generate  # For situation generation and resolution

    async def process_tick(
        self,
        character: PlayerCharacter,
        world_context: str,
        threat_type: str = "",
        world_state: str = "",
        interval_minutes: int = 30,
        room_id: str = "",
    ) -> Optional[BackgroundTickResult]:
        """
        Process a single background tick for a separated character.

        FULL SIMULATION MODE: This character gets the SAME systems as the player:
        - Opening matrix context from separation
        - DM Council deliberates decisions (MEDIUM/MAJOR)
        - Real inventory updates
        - Real condition progression (hunger/thirst/injuries)
        - Real fatigue progression

        Args:
            character: The separated character
            world_context: Description of the world/scenario
            threat_type: What kind of threats exist
            world_state: Current state of civilization
            interval_minutes: Time elapsed - affects event drama:
                < 5 min: Mundane (resting, small observations)
                5-30 min: Minor (found something, brief encounter)
                30-60 min: Meaningful (decisions, discoveries)
                60+ min: Major (combat, significant changes)
            room_id: Room ID for tracker access
        """
        if not character.is_separated or not character.is_alive:
            return None

        # === RICH DEBUG OUTPUT: FULL SIMULATION TICK ===
        print(f"\n{'='*70}")
        print(f"  FULL SIMULATION TICK: {character.character_name.upper()}")
        print(f"{'='*70}")
        print(f"  Time elapsed: {interval_minutes} minutes ({interval_minutes/60:.1f} hours)")
        print(f"  Location: {character.last_known_location or 'Unknown'}")
        print(f"  Current state: {character.condition} | Supplies: {character.supplies_status} | Morale: {character.morale}")

        # === FULL SIMULATION: PROGRESS TIME-BASED SYSTEMS ===
        hours_elapsed = interval_minutes / 60.0
        character.hours_since_separation = getattr(character, 'hours_since_separation', 0) + hours_elapsed
        print(f"  Hours since separation: {character.hours_since_separation:.1f}h")

        # Progress hunger/thirst/fatigue based on elapsed time
        print(f"\n  [TIME PROGRESSION]")
        self._progress_condition_over_time(character, hours_elapsed, room_id)
        self._progress_fatigue_over_time(character, hours_elapsed, room_id)

        # Get matrix context for richer situation generation
        matrix_context = self._get_matrix_context(character)
        if matrix_context:
            print(f"\n  [MATRIX CONTEXT]")
            for line in matrix_context.split('\n'):
                print(f"    {line}")

        # Build enriched world context with matrix info
        enriched_context = world_context
        if matrix_context:
            enriched_context = f"{world_context}\n\n=== CHARACTER'S CURRENT SITUATION ===\n{matrix_context}"

        # 1. Generate a situation (drama scales with interval)
        print(f"\n  [GENERATING SITUATION...]")
        situation = await self._generate_situation(
            character, enriched_context, threat_type, world_state, interval_minutes
        )
        print(f"\n  [SITUATION GENERATED]")
        print(f"    Type: {situation.situation_type.value.upper()}")
        print(f"    Difficulty: {situation.difficulty}/10")
        print(f"    Time pressure: {'YES' if situation.time_pressure else 'No'}")
        print(f"    Description: {situation.description[:200]}...")
        print(f"    Options:")
        for i, opt in enumerate(situation.options, 1):
            print(f"      {i}. {opt}")

        # 2. Get character's response
        print(f"\n  [CHARACTER DECIDING...]")
        response = await self._get_character_response(character, situation)
        print(f"\n  [CHARACTER RESPONSE]")
        print(f"    {response[:300]}...")

        # 3. Resolve the outcome using DM Council for meaningful decisions
        print(f"\n  [COUNCIL DELIBERATION...]")
        result = await self._resolve_outcome_with_council(
            character, situation, response, enriched_context, room_id
        )
        print(f"\n  [OUTCOME]")
        print(f"    {result.outcome[:300]}...")
        if result.condition_change:
            print(f"    Condition change: {result.condition_change}")
        if result.supplies_change:
            print(f"    Supplies change: {result.supplies_change}")
        if result.morale_change:
            print(f"    Morale change: {result.morale_change}")
        if result.discovery:
            print(f"    Discovery: {result.discovery}")

        # 4. Update character state (with real tracker integration)
        print(f"\n  [APPLYING RESULTS TO TRACKERS...]")
        self._apply_result(character, result, room_id)

        # 5. Mark tick as processed
        character.record_background_tick()
        # Expand search radius based on actual interval
        hours_elapsed = interval_minutes / 60.0
        character.expand_search_radius(hours_elapsed=hours_elapsed)

        print(f"\n  [TICK COMPLETE]")
        print(f"    New state: {character.condition} | Supplies: {character.supplies_status} | Morale: {character.morale}")
        print(f"    Search radius: {character.search_radius_km:.1f} km")
        print(f"{'='*70}\n")

        return result

