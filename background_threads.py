    def _parse_situation(self, response: str, situation_type: SituationType) -> BackgroundSituation:
        """Parse a generated situation from the DM response."""
        description = ""
        options = []
        difficulty = 5
        rewards = []
        risks = []

        lines = response.strip().split('\n')
        current_section = None

        for line in lines:
            line = line.strip()
            if line.startswith("SITUATION:"):
                description = line[10:].strip()
                current_section = "situation"
            elif line.startswith("OPTIONS:"):
                current_section = "options"
            elif line.startswith("DIFFICULTY:"):
                try:
                    difficulty = int(line[11:].strip().split()[0])
                except:
                    pass
                current_section = None
            elif line.startswith("REWARDS:"):
                rewards = [r.strip() for r in line[8:].split(',')]
                current_section = None
            elif line.startswith("RISKS:"):
                risks = [r.strip() for r in line[6:].split(',')]
                current_section = None
            elif current_section == "situation" and line:
                description += " " + line
            elif current_section == "options" and line:
                # Remove numbering
                if line[0].isdigit() and len(line) > 2:
                    line = line[2:].strip()
                if line.startswith('.'):
                    line = line[1:].strip()
                if line:
                    options.append(line)

        # Ensure we have at least some options
        if not options:
            options = ["Take careful action", "Wait and observe", "Move to a different area"]

        return BackgroundSituation(
            situation_type=situation_type,
            description=description or "A moment of uncertainty in the wasteland.",
            options=options[:3],
            difficulty=min(10, max(1, difficulty)),
            potential_rewards=rewards,
            potential_risks=risks,
            time_pressure=random.random() < 0.3,
        )

